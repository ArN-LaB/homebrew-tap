    def test_git_source_and_build_receipt_and_readonly_plan(self):
        project = self.root / "project"
        project.mkdir()
        installer.run(["git", "init", "-q", project])
        installer.run(["git", "-C", project, "remote", "add", "origin", "git@github.com:ArN-LaB/fixture.git"])
        (project / ".macos-local-install.json").write_text(json.dumps(CONFIG))
        (project / "fixture.c").write_text("int main(void) { return 0; }\n")
        (project / "make_app.py").write_text(
            "from pathlib import Path\nimport plistlib,subprocess\n"
            "p=Path('Fixture.app/Contents'); (p/'MacOS').mkdir(parents=True)\n"
            "(p/'Info.plist').write_bytes(plistlib.dumps(" + repr(plistlib.loads((self.bundle / "Contents/Info.plist").read_bytes())) + "))\n"
            "subprocess.run(['clang','fixture.c','-o',str(p/'MacOS/Fixture')],check=True)\n"
            "subprocess.run(['codesign','--sign','-','--timestamp=none','Fixture.app'],check=True)\n")
        installer.run(["git", "-C", project, "add", ".macos-local-install.json", "fixture.c", "make_app.py"])
        installer.run(["git", "-c", "user.name=Fixture", "-c", "user.email=fixture@example.invalid", "-c", "commit.gpgsign=false", "-C", project, "commit", "-qm", "fixture"])
        before = installer.digest(project)
        index_mtime = (project / ".git/index").stat().st_mtime_ns
        planned = subprocess.run([sys.executable, "-B", str(SCRIPT), "--project", str(project), "--dry-run"], capture_output=True, text=True)
        self.assertEqual(planned.returncode, 0, planned.stderr)
        self.assertEqual(installer.digest(project), before)
        self.assertEqual((project / ".git/index").stat().st_mtime_ns, index_mtime)
        with contextlib.redirect_stdout(io.StringIO()):
            app, receipt = installer.build(project, CONFIG, self.state)
        self.assertEqual(installer.trusted(app, receipt, CONFIG, self.state)["bundle_id"], CONFIG["bundle_id"])
        (project / "fixture.c").write_text("changed")
        with self.assertRaises(installer.Refusal):
            installer.repository(project, CONFIG["repository"])

