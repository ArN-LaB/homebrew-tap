    def test_source_dependency_pinning_rejects_other_head_and_dirty_tree(self):
        project = self.root / "dependency"
        project.mkdir()
        installer.run(["git", "init", "-q", project])
        installer.run(["git", "-C", project, "remote", "add", "origin", "git@github.com:ArN-LaB/fixture.git"])
        (project / "source.txt").write_text("source")
        installer.run(["git", "-C", project, "add", "source.txt"])
        installer.run(["git", "-c", "user.name=Fixture", "-c", "user.email=fixture@example.invalid", "-c", "commit.gpgsign=false", "-C", project, "commit", "-qm", "fixture"])
        commit = installer.git(project, "rev-parse", "HEAD")
