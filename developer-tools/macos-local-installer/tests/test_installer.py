    def test_exclusive_publication_preserves_competing_destination(self):
        source, target = self.root / "source", self.root / "target"
        source.write_text("ours")
        target.write_text("foreign")
        with self.assertRaises(OSError):
            installer.move_exclusive(source, target)
        self.assertEqual(target.read_text(), "foreign")
        self.assertEqual(source.read_text(), "ours")

    def test_failed_publication_restores_existing_bundle(self):
        self.install()
        target = self.destination / "Fixture.app"
        before = installer.identity(target)
        real_move = installer.move_exclusive
        def fail_publish(source, destination):
            if Path(source).name == "prepared.app":
                raise OSError("simulated publication failure")
            return real_move(source, destination)
        with mock.patch.object(installer, "move_exclusive", side_effect=fail_publish):
            with self.assertRaises(OSError):
                self.install()
        self.assertEqual(installer.identity(target), before)

    def test_concurrent_replacement_is_not_overwritten(self):
        self.install()
        target = self.destination / "Fixture.app"
        real_move = installer.move_exclusive
        def collide(source, destination):
            if Path(source).name == "prepared.app":
                target.mkdir()
                (target / "foreign").write_text("preserve")
            return real_move(source, destination)
        with mock.patch.object(installer, "move_exclusive", side_effect=collide):
            with self.assertRaises(OSError):
                self.install()
        self.assertEqual((target / "foreign").read_text(), "preserve")
        self.assertTrue(list((self.destination / ".arnlab-local-installer").glob("*/previous.app")))

