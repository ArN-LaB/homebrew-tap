SCRIPT = Path(__file__).resolve().parents[1] / "installer.py"
spec = importlib.util.spec_from_file_location("installer", SCRIPT)
installer = importlib.util.module_from_spec(spec)
spec.loader.exec_module(installer)
CONFIG = {"bundle_name": "Fixture.app", "bundle_id": "com.arn-lab.fixture",
          "repository": "ArN-LaB/fixture", "component_version": installer.VERSION,
          "build": ["{python}", "make_app.py"], "output": "Fixture.app"}


@unittest.skipUnless(sys.platform == "darwin", "native macOS campaign required")
class InstallerTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.shared = tempfile.TemporaryDirectory(prefix="arnlab-native-fixture-")
        cls.base = Path(cls.shared.name).resolve()
        cls.bundle = cls.base / "Fixture.app"
        (cls.bundle / "Contents/MacOS").mkdir(parents=True)
        (cls.bundle / "Contents/Info.plist").write_bytes(plistlib.dumps({
            "CFBundleIdentifier": CONFIG["bundle_id"], "CFBundleExecutable": "Fixture",
            "CFBundlePackageType": "APPL", "CFBundleShortVersionString": "1.0"}))
        source = cls.base / "fixture.c"
        source.write_text("int main(void) { return 0; }\n")
        installer.run(["/usr/bin/clang", source, "-o", cls.bundle / "Contents/MacOS/Fixture"])
        installer.run(["/usr/bin/codesign", "--sign", "-", "--timestamp=none", cls.bundle])

    @classmethod
    def tearDownClass(cls):
        cls.shared.cleanup()

    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="arnlab-installer-test-")
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name).resolve()
        self.state = self.root / "state"
        self.destination = self.root / "Applications-simulation"
        self.destination.mkdir()
        self.app = self.root / "Fixture.app"
        shutil.copytree(self.bundle, self.app, symlinks=True)
        self.receipt = self.issue(self.app)
        self.caskroom = self.root / "Caskroom"
        patch = mock.patch.object(installer, "CASKROOMS", (self.caskroom,))
        patch.start(); self.addCleanup(patch.stop)
        patch = mock.patch.object(installer, "running_applications", return_value=[])
        self.running = patch.start(); self.addCleanup(patch.stop)

    def issue(self, app, config=CONFIG):
        installer.private_directory(self.state)
        receipt = str(uuid.uuid4())
        installer.save_new(self.state / (receipt + ".json"), {
            "schema": 1, "id": receipt, "source": {"repository": config["repository"]},
            "result": installer.verify(app, config)})
        return receipt

    def cask(self, bundle_name="Fixture.app"):
        metadata = self.caskroom / "fixture/.metadata"
        metadata.mkdir(parents=True)
        (metadata / "config.json").write_text(json.dumps({"default": {"appdir": str(self.destination)}}))
        (metadata / "INSTALL_RECEIPT.json").write_text(json.dumps({"uninstall_artifacts": [{"app": [bundle_name]}]}))

    def linker_only(self):
        shutil.rmtree(self.app / "Contents/_CodeSignature")  # Fixture generated by this test only.
        source = self.root / "fixture.c"
        source.write_text("int main(void) { return 0; }\n")
        installer.run(["/usr/bin/clang", source, "-o", self.app / "Contents/MacOS/Fixture"])

    def install(self, app=None, receipt=None, consent=lambda *_: True):
        with contextlib.redirect_stdout(io.StringIO()):
            return installer.install(app or self.app, receipt or self.receipt, CONFIG,
                                     self.state, self.destination, consent)

    def test_signed_bundle_native_verification(self):
        self.assertEqual(installer.verify(self.app, CONFIG)["signature"], "ad hoc valide")

    def test_valid_bundle_signature_is_never_replaced(self):
        before = installer.digest(self.app)
        installer.finalize_local_linker_signature(self.app)
        self.assertEqual(installer.digest(self.app), before)

    def test_new_linker_only_signature_gets_resource_seal(self):
        (self.app / "Contents/_CodeSignature/CodeResources").unlink()
        (self.app / "Contents/_CodeSignature").rmdir()
        source = self.root / "fixture.c"
        source.write_text("int main(void) { return 0; }\n")
        installer.run(["/usr/bin/clang", source, "-o", self.app / "Contents/MacOS/Fixture"])
        with self.assertRaises(installer.Refusal):
            installer.verify(self.app, CONFIG)
        with contextlib.redirect_stdout(io.StringIO()):
            installer.finalize_local_linker_signature(self.app)
        self.assertEqual(installer.verify(self.app, CONFIG)["signature"], "ad hoc valide")

    def test_invalid_bundle_signature_is_not_repaired(self):
        with (self.app / "Contents/MacOS/Fixture").open("ab") as stream:
            stream.write(b"corruption")
        before = installer.digest(self.app)
        with self.assertRaises(installer.Refusal):
            installer.finalize_local_linker_signature(self.app)
        self.assertEqual(installer.digest(self.app), before)

    def test_unsigned_local_bundle_supported(self):
        (self.app / "Contents/_CodeSignature/CodeResources").unlink()
        (self.app / "Contents/_CodeSignature").rmdir()
        installer.run(["/usr/bin/codesign", "--remove-signature", self.app / "Contents/MacOS/Fixture"])
        self.assertIn("non signé", installer.verify(self.app, CONFIG)["signature"])

    def test_install_preserves_source_signature_and_content(self):
        before = installer.digest(self.app)
        transaction = self.install()
        self.assertEqual(installer.digest(self.destination / "Fixture.app"), before)
        self.assertEqual(installer.digest(self.app), before)
        self.assertTrue((self.destination / ".arnlab-local-installer" / transaction / "installed.json").is_file())

    def test_update_backup_and_rollback(self):
        self.install()
        original = installer.digest(self.destination / "Fixture.app")
        # A distinct valid source build, signed only inside this test fixture.
        info = plistlib.loads((self.app / "Contents/Info.plist").read_bytes())
        info["CFBundleShortVersionString"] = "2.0"
        (self.app / "Contents/Info.plist").write_bytes(plistlib.dumps(info))
        installer.run(["/usr/bin/codesign", "--force", "--sign", "-", "--timestamp=none", self.app])
        receipt = self.issue(self.app)
        transaction = self.install(receipt=receipt)
        directory = self.destination / ".arnlab-local-installer" / transaction
        self.assertEqual(installer.digest(directory / "previous.app"), original)
        with contextlib.redirect_stdout(io.StringIO()):
            installer.rollback(transaction, CONFIG, self.destination, lambda *_: True)
        self.assertEqual(installer.digest(self.destination / "Fixture.app"), original)
        self.assertTrue((directory / "replaced.app").exists())

    def test_cancel_does_not_touch_destination(self):
        with self.assertRaises(installer.Refusal):
            self.install(consent=lambda *_: False)
        self.assertEqual(list(self.destination.iterdir()), [])

    def test_quarantine_requires_separate_approval_and_source_is_preserved(self):
        installer.run(["/usr/bin/xattr", "-w", installer.QUARANTINE, "0081;12345678;Fixture;", self.app])
        answers = iter([True, False])
        with self.assertRaises(installer.Refusal):
            self.install(consent=lambda *_: next(answers))
        self.assertFalse((self.destination / "Fixture.app").exists())
        self.assertTrue(installer.quarantine_paths(self.app))
        calls = []
        self.install(consent=lambda message, word: calls.append(word) or True)
        self.assertEqual(calls, ["INSTALLER", "RETIRER"])
        self.assertTrue(installer.quarantine_paths(self.app))
        self.assertEqual(installer.quarantine_paths(self.destination / "Fixture.app"), [])

